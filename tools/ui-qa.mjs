import { chromium } from '@playwright/test';
import { resolve } from 'node:path';

const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
const check = (name, pass) => { if (!pass) throw new Error(name); console.log(`PASS ${name}`); };
await page.goto('http://127.0.0.1:4186/', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__palace?.ready, { timeout: 90000 });
await page.waitForTimeout(2200);
check('手机首屏无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
await page.screenshot({ path: resolve('docs/screenshots/mobile.png') });
await page.locator('#nav-toggle').click();
await page.waitForTimeout(400);
await page.screenshot({ path: resolve('docs/screenshots/mobile-directory.png') });
await page.locator('#building-search').fill('太和殿');
await page.locator('#building-list [data-pick]').first().click();
await page.waitForTimeout(1800);
await page.screenshot({ path: resolve('docs/screenshots/mobile-selected.png') });
check('手机建筑详情显示', await page.locator('#building-detail').isVisible());
check('手机详情无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
await page.locator('#detail-back').click();
check('手机返回列表隐藏详情', await page.locator('#building-search').isVisible() && await page.locator('#building-detail').isHidden());
await page.setViewportSize({ width: 1280, height: 720 });
await page.waitForTimeout(1000);
check('桌面无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
await page.locator('#building-list [data-pick]').first().click();
await page.waitForTimeout(1800);
check('桌面选择建筑收起列表', await page.locator('#building-search').isHidden() && await page.locator('#building-detail').isVisible());
await page.locator('#detail-back').click();
check('桌面返回建筑列表', await page.locator('#building-search').isVisible() && await page.locator('#building-detail').isHidden());
await browser.close();
